/// Frozen execution image facts (authoritative design "Execution Image And
/// Target Pinning"). The store treats this as an immutable, authenticated
/// reference; it never resolves "latest" at execution time.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase", deny_unknown_fields)]
pub struct TaskExecutionImageRef {
    pub target_environment: String,
    pub package_version: String,
    pub assembly: RuntimeAssemblyRef,
    pub config_snapshot: RuntimeConfigSnapshotRef,
    pub deployment: ServiceDeploymentRef,
}

/// Already-encoded recoverable payload bytes. The store is deliberately
/// payload-agnostic: decode uses the execution image's linked expected plan at
/// attempt time and is owned by the execution layer.
#[derive(Debug, Clone, PartialEq, Eq, Hash, Default)]
pub struct RecoverablePayload(Vec<u8>);

impl RecoverablePayload {
    pub fn new(bytes: Vec<u8>) -> Self {
        Self(bytes)
    }

    pub fn as_bytes(&self) -> &[u8] {
        &self.0
    }

    pub fn into_bytes(self) -> Vec<u8> {
        self.0
    }
}

/// Frozen actor activation facts needed to recover a minimal registry entry
/// and run `create` when no live incarnation exists.
#[derive(Debug, Clone, PartialEq)]
pub struct ActorActivationSnapshot {
    pub key: RecoverablePayload,
    pub create_input: RecoverablePayload,
    /// Artifact-form expected-type plan for the frozen create input (store
    /// witness). Execution decodes against linked expected plans, never this
    /// projection.
    pub expected_type_plan: RecoverableExpectedTypePlan,
    /// Runtime-form recoverable expected-type plan as frozen by the
    /// submission side (E2a wire `expectedTypePlan`). The runtime form is the
    /// only plan the Runtime can freeze from the linked program; the artifact
    /// projection above is a store-compatible witness. `None` for records
    /// created before this field existed (C1 compatibility).
    pub expected_type_plan_runtime: Option<serde_json::Value>,
}

