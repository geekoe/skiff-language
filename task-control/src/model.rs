/// Platform error classification entry: permanent errors converge to terminal
/// `platform-failed`; transient errors keep the TaskId and are retried with
/// bounded backoff by the scheduler.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum PlatformErrorClass {
    Permanent,
    Transient,
}

impl PlatformErrorClass {
    pub fn permanent() -> Self {
        Self::Permanent
    }

    pub fn transient() -> Self {
        Self::Transient
    }

    pub fn is_permanent(&self) -> bool {
        matches!(self, Self::Permanent)
    }

    /// Returns the terminal outcome for permanent errors; transient errors
    /// do not converge and must not be settled as terminal.
    pub fn terminal_outcome(self, reason: impl Into<String>) -> Option<TaskOutcome> {
        match self {
            Self::Permanent => Some(TaskOutcome::PlatformFailed {
                reason: reason.into(),
            }),
            Self::Transient => None,
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn status_kinds_match_reference_spelling() {
        for kind in [
            TaskStatusKind::Scheduled,
            TaskStatusKind::Ready,
            TaskStatusKind::Running,
            TaskStatusKind::Succeeded,
            TaskStatusKind::Failed,
            TaskStatusKind::PlatformFailed,
            TaskStatusKind::Canceled,
            TaskStatusKind::Expired,
        ] {
            let value = serde_json::to_value(TaskStatus { kind }).expect("serialize");
            assert_eq!(value["kind"], serde_json::json!(kind_name(kind)));
        }
        for kind in [
            TaskCancelResultKind::Canceled,
            TaskCancelResultKind::AlreadyStarted,
            TaskCancelResultKind::AlreadyTerminal,
            TaskCancelResultKind::Expired,
        ] {
            let value = serde_json::to_value(TaskCancelResult { kind }).expect("serialize");
            assert_eq!(value["kind"], serde_json::json!(cancel_kind_name(kind)));
        }
    }

    fn kind_name(kind: TaskStatusKind) -> &'static str {
        match kind {
            TaskStatusKind::Scheduled => "scheduled",
            TaskStatusKind::Ready => "ready",
            TaskStatusKind::Running => "running",
            TaskStatusKind::Succeeded => "succeeded",
            TaskStatusKind::Failed => "failed",
            TaskStatusKind::PlatformFailed => "platformFailed",
            TaskStatusKind::Canceled => "canceled",
            TaskStatusKind::Expired => "expired",
        }
    }

    fn cancel_kind_name(kind: TaskCancelResultKind) -> &'static str {
        match kind {
            TaskCancelResultKind::Canceled => "canceled",
            TaskCancelResultKind::AlreadyStarted => "alreadyStarted",
            TaskCancelResultKind::AlreadyTerminal => "alreadyTerminal",
            TaskCancelResultKind::Expired => "expired",
        }
    }

    #[test]
    fn platform_error_classification_converges_only_permanent_errors() {
        let permanent = PlatformErrorClass::permanent();
        assert!(permanent.is_permanent());
        let outcome = permanent
            .terminal_outcome("execution record deleted")
            .expect("permanent converges");
        assert_eq!(outcome.terminal_state(), TaskState::PlatformFailed);

        let transient = PlatformErrorClass::transient();
        assert!(!transient.is_permanent());
        assert_eq!(
            transient.terminal_outcome("runtime unavailable"),
            None,
            "transient errors must not converge to terminal"
        );
    }

    #[test]
    fn task_state_ascii_spelling_is_stable() {
        assert_eq!(TaskState::Scheduled.as_str(), "scheduled");
        assert_eq!(TaskState::Ready.as_str(), "ready");
        assert_eq!(TaskState::Leased.as_str(), "leased");
        assert_eq!(TaskState::Succeeded.as_str(), "succeeded");
        assert_eq!(TaskState::Failed.as_str(), "failed");
        assert_eq!(TaskState::PlatformFailed.as_str(), "platformFailed");
        assert_eq!(TaskState::Canceled.as_str(), "canceled");
        assert!(TaskState::Succeeded.is_terminal());
        assert!(TaskState::Failed.is_terminal());
        assert!(TaskState::PlatformFailed.is_terminal());
        assert!(TaskState::Canceled.is_terminal());
        assert!(!TaskState::Scheduled.is_terminal());
        assert!(!TaskState::Ready.is_terminal());
        assert!(!TaskState::Leased.is_terminal());
    }
}
