//! Canonical durable task record model.
//!
//! Field ownership follows `doc/architecture/durable-task-dispatch.md`
//! (Canonical Task Identity And Record). The structs here are the store
//! authority facts; physical storage schemas (Mongo DTO) are adapters over
//! this model. Identity types are reused from `skiff-artifact-model` /
//! `skiff-deployment` where the repo already owns the canonical form.

use std::fmt;

