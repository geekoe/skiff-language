/// Opaque task identity. Generated by the submission side before the first
/// physical write; the store only persists and compares it.
#[derive(Debug, Clone, PartialEq, Eq, PartialOrd, Ord, Hash, Serialize, Deserialize)]
#[serde(transparent)]
pub struct TaskId(String);

/// Opaque attempt identity. A fresh value is created on every successful claim.
