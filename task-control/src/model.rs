/// Canonical task record. Field ownership follows the authoritative design;
/// all transitions are conditional writes against this record.
#[derive(Debug, Clone, PartialEq)]
pub struct TaskRecord {
    pub task_id: TaskId,
    pub owner: ServiceOwner,
    pub execution: TaskExecutionImageRef,
    pub target: DetachedCallTarget,
    pub payload: RecoverablePayload,
    pub due_at: DurableUtcTimestamp,
    pub state: TaskState,
    pub attempt_generation: u64,
    pub active_lease: Option<TaskLease>,
    pub terminal: Option<TaskTerminal>,
    pub trace: TaskTraceContext,
    pub created_at: DurableUtcTimestamp,
    /// Scheduler-owned platform backoff: when set, no new attempt may be
    /// claimed before this durable store-authority timestamp. It is written
    /// atomically by lease-expiry recovery and provable-rejection release;
    /// submission leaves it `None`, and `claim` does not clear it (a past
    /// value is inert). It is not a user-facing retry policy.
    pub retry_not_before: Option<DurableUtcTimestamp>,
    /// Test-case authority captured at submission (F2a). When present the
    /// task attempt is a derived request of the parent test case: it carries
    /// the same opaque capability and test-effects-enabled admission, and it
    /// must execute on the exact origin Runtime connection with the parent
    /// service. Ordinary production tasks leave this `None` and keep the
    /// location-transparent scheduler semantics unchanged.
    pub test_case: Option<TaskTestCaseAuthority>,
}

/// Router-derived test-case authority persisted with one task record.
///
/// The wire `task.submit.request` deliberately carries only `callerRequestId`
/// (never the capability or parent id); the Router derives these facts from
/// the still-active parent request / Actor invocation on the exact same
/// Runtime connection. Durable attempts later re-enter the case through the
/// same capability, and admission enforces the origin connection / service.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct TaskTestCaseAuthority {
    /// Opaque Router-issued test case capability (test-runner-runtime
    /// isolation contract; never a Skiff value or business effect API).
    pub test_case_capability: String,
    /// Active parent request / Actor invocation id that submitted the task.
    pub parent_request_id: String,
    /// Exact origin Runtime replica that submitted the task.
    pub origin_runtime_id: String,
    /// Exact origin WebSocket connection generation on that replica.
    pub origin_connection_generation: u64,
}

impl TaskRecord {
    /// Initial-record validation for `create`: a task enters the store as
    /// `scheduled` with no lease / terminal and generation zero.
    pub fn validate_create(&self) -> Result<(), String> {
        if self.state != TaskState::Scheduled {
            return Err(format!(
                "task {} must be created in scheduled state, found {}",
                self.task_id, self.state
            ));
        }
        if self.attempt_generation != 0 {
            return Err(format!(
                "task {} must start with attempt generation 0",
                self.task_id
            ));
        }
        if self.active_lease.is_some() {
            return Err(format!(
                "task {} cannot be created with an active lease",
                self.task_id
            ));
        }
        if self.terminal.is_some() {
            return Err(format!(
                "task {} cannot be created with a terminal",
                self.task_id
            ));
        }
        if self.created_at.millis() < 0 || self.due_at.millis() < 0 {
            return Err(format!(
                "task {} timestamps must be non-negative epoch millis",
                self.task_id
            ));
        }
        Ok(())
    }

    pub fn status_kind(&self) -> TaskStatusKind {
        match self.state {
            TaskState::Scheduled => TaskStatusKind::Scheduled,
            TaskState::Ready => TaskStatusKind::Ready,
            TaskState::Leased => TaskStatusKind::Running,
            TaskState::Succeeded => TaskStatusKind::Succeeded,
            TaskState::Failed => TaskStatusKind::Failed,
            TaskState::PlatformFailed => TaskStatusKind::PlatformFailed,
            TaskState::Canceled => TaskStatusKind::Canceled,
        }
    }
}

