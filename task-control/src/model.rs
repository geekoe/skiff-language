/// Canonical task state machine (authoritative design "State Machine").
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub enum TaskState {
    Scheduled,
    Ready,
    Leased,
    Succeeded,
    Failed,
    PlatformFailed,
    Canceled,
}

impl TaskState {
    pub fn is_terminal(&self) -> bool {
        matches!(
            self,
            Self::Succeeded | Self::Failed | Self::PlatformFailed | Self::Canceled
        )
    }

    pub fn as_str(&self) -> &'static str {
        match self {
            Self::Scheduled => "scheduled",
            Self::Ready => "ready",
            Self::Leased => "leased",
            Self::Succeeded => "succeeded",
            Self::Failed => "failed",
            Self::PlatformFailed => "platformFailed",
            Self::Canceled => "canceled",
        }
    }
}

impl fmt::Display for TaskState {
    fn fmt(&self, formatter: &mut fmt::Formatter<'_>) -> fmt::Result {
        formatter.write_str(self.as_str())
    }
}

/// One valid execution attempt lease. Fencing is lease-id based: every
/// settlement / heartbeat must carry the current lease id.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct TaskLease {
    pub lease_id: LeaseId,
    pub attempt_id: AttemptId,
    pub owner: String,
    pub expiry: DurableUtcTimestamp,
}

/// Canonical terminal outcome. The terminal state is derived from the
/// outcome; identity of a settlement is `outcome` equality.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(tag = "kind", rename_all = "camelCase")]
pub enum TaskOutcome {
    /// Target returned normally.
    Succeeded,
    /// Target explicitly threw / rejected.
    TargetFailed { error: String },
    /// Platform proved the task can never form a legal execution attempt.
    PlatformFailed { reason: String },
    /// Before-start cancellation converged.
    Canceled,
}

impl TaskOutcome {
    pub fn terminal_state(&self) -> TaskState {
        match self {
            Self::Succeeded => TaskState::Succeeded,
            Self::TargetFailed { .. } => TaskState::Failed,
            Self::PlatformFailed { .. } => TaskState::PlatformFailed,
            Self::Canceled => TaskState::Canceled,
        }
    }
}

/// Durable terminal record written by one settlement CAS.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct TaskTerminal {
    pub settled_at: DurableUtcTimestamp,
    pub outcome: TaskOutcome,
}

impl TaskTerminal {
    pub fn state(&self) -> TaskState {
        self.outcome.terminal_state()
    }

    pub fn same_outcome(&self, other: &Self) -> bool {
        self.outcome == other.outcome
    }
}

