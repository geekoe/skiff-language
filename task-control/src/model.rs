macro_rules! as_str_impl {
    ($ty:ty) => {
        impl AsRef<str> for $ty {
            fn as_ref(&self) -> &str {
                self.as_str()
            }
        }

        impl From<String> for $ty {
            fn from(value: String) -> Self {
                Self::new(value)
            }
        }

        impl From<&str> for $ty {
            fn from(value: &str) -> Self {
                Self::new(value)
            }
        }

        impl fmt::Display for $ty {
            fn fmt(&self, formatter: &mut fmt::Formatter<'_>) -> fmt::Result {
                formatter.write_str(self.as_str())
            }
        }
    };
}

as_str_impl!(TaskId);
as_str_impl!(AttemptId);
as_str_impl!(LeaseId);
as_str_impl!(ServiceOwner);

/// Canonical UTC epoch timestamp in milliseconds.
///
/// This is a durable, cross-host comparable timestamp, not a process-local
/// monotonic `Instant`. Due visibility, lease expiry and expiry races use the
/// TaskStore authority clock; this type only carries the durable value.
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Hash, Serialize, Deserialize)]
#[serde(transparent)]
pub struct DurableUtcTimestamp(i64);

impl DurableUtcTimestamp {
    pub fn from_millis(millis: i64) -> Self {
        Self(millis)
    }

    pub fn millis(&self) -> i64 {
        self.0
    }

    pub fn checked_add_millis(self, millis: i64) -> Option<Self> {
        self.0.checked_add(millis).map(Self)
    }
}

impl fmt::Display for DurableUtcTimestamp {
    fn fmt(&self, formatter: &mut fmt::Formatter<'_>) -> fmt::Result {
        write!(formatter, "{}", self.0)
    }
}

